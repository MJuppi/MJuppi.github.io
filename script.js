document.addEventListener("DOMContentLoaded", () => {
  const navLinks = document.querySelectorAll(".nav-link");
  const sections = document.querySelectorAll(".section");
  const modelLinks = document.querySelectorAll(".model-link");
  const models = document.querySelectorAll(".model");
  const languageToggle = document.getElementById("languageToggle");
  const typingTextEl = document.getElementById("typingText");

  function getPreferredLanguage() {
    const stored = localStorage.getItem("lang");
    if (stored === "en" || stored === "fi") return stored;
    return navigator.language &&
      navigator.language.toLowerCase().startsWith("fi")
      ? "fi"
      : "en";
  }

  function updateLanguageToggle(lang) {
    if (!languageToggle) return;
    languageToggle.textContent = lang === "en" ? "🇫🇮" : "🇬🇧";
    languageToggle.setAttribute(
      "aria-label",
      lang === "en" ? "Switch to Finnish" : "Switch to English",
    );
    languageToggle.title =
      lang === "en" ? "Vaihda suomeksi" : "Switch to English";
  }

  function updateTranslations(lang) {
    const dict = translations[lang] || translations.en;
    document.documentElement.lang = lang;
    document.documentElement.setAttribute("data-lang", lang);

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const value = dict[el.dataset.i18n];
      if (value) el.textContent = value;
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const value = dict[el.dataset.i18nAria];
      if (value) el.setAttribute("aria-label", value);
    });

    updateLanguageToggle(lang);
    localStorage.setItem("lang", lang);
  }

  const typingPhrases = {
    en: [
      "Full-Stack Developer",
      "3D Modeling Enthusiast",
      "Local AI Explorer",
      "Creative Problem Solver",
    ],
    fi: [
      "Full-Stack-kehittäjä",
      "3D-mallinnuksen harrastaja",
      "Paikallinen AI-keksijä",
      "Luova ongelmanratkaisija",
    ],
  };

  let lang = getPreferredLanguage();
  let typingPhrasesList = typingPhrases[lang] || typingPhrases.en;
  let phraseIndex = 0;
  let charIndex = 0;
  let isDeleting = false;
  let typingSpeed = 80;
  let typingTimer = null;

  function type() {
    const currentPhrase = typingPhrasesList[phraseIndex];

    if (isDeleting) {
      typingTextEl.textContent = currentPhrase.substring(0, charIndex - 1);
      charIndex--;
      typingSpeed = 40;
    } else {
      typingTextEl.textContent = currentPhrase.substring(0, charIndex + 1);
      charIndex++;
      typingSpeed = 80;
    }

    if (!isDeleting && charIndex === currentPhrase.length) {
      typingSpeed = 2000;
      isDeleting = true;
    } else if (isDeleting && charIndex === 0) {
      isDeleting = false;
      phraseIndex = (phraseIndex + 1) % typingPhrasesList.length;
      typingSpeed = 500;
    }

    typingTimer = setTimeout(type, typingSpeed);
  }

  updateTranslations(lang);
  typingPhrasesList = typingPhrases[lang] || typingPhrases.en;
  type();

  if (languageToggle) {
    languageToggle.addEventListener("click", () => {
      clearTimeout(typingTimer);
      lang = lang === "en" ? "fi" : "en";
      typingPhrasesList = typingPhrases[lang] || typingPhrases.en;
      phraseIndex = 0;
      charIndex = 0;
      isDeleting = false;
      updateTranslations(lang);
      typingTextEl.textContent = "";
      type();
    });
  }

  navLinks.forEach((link) => {
    link.addEventListener("click", (e) => {
      e.preventDefault();

      // Remove active from all links and mark the current one for screen readers
      navLinks.forEach((l) => {
        l.classList.remove("active");
        if (l === link) {
          l.setAttribute("aria-current", "page");
        } else {
          l.removeAttribute("aria-current");
        }
      });
      link.classList.add("active");

      // Hide all sections
      sections.forEach((sec) => sec.classList.remove("active"));

      // Show the target section
      const targetId = link.getAttribute("data-target");
      const targetSection = document.getElementById(targetId);
      if (targetSection) {
        targetSection.classList.add("active");
      }
    });
  });

  modelLinks.forEach((link) => {
    link.addEventListener("click", (e) => {
      e.preventDefault();

      // Remove active from all model links and mark the current one for screen readers
      modelLinks.forEach((l) => {
        l.classList.remove("active");
        if (l === link) {
          l.setAttribute("aria-current", "page");
        } else {
          l.removeAttribute("aria-current");
        }
      });
      link.classList.add("active");

      // Hide all models
      models.forEach((model) => model.classList.remove("active"));

      // Show the target model
      const targetId = link.getAttribute("model-target");
      const targetModel = document.getElementById(targetId);
      if (targetModel) {
        targetModel.classList.add("active");
      }
    });
  });

  // ===== KEYBOARD NAVIGATION FOR SIDEBAR TABS =====
  function enableArrowNavigation(listEl) {
    const links = Array.from(listEl.querySelectorAll("a"));
    listEl.addEventListener("keydown", (e) => {
      let nextIndex;
      const current = links.indexOf(document.activeElement);
      if (e.key === "ArrowDown") {
        nextIndex = current < 0 ? 0 : (current + 1) % links.length;
      } else if (e.key === "ArrowUp") {
        nextIndex =
          current < 0
            ? links.length - 1
            : (current - 1 + links.length) % links.length;
      } else if (e.key === "Home") {
        nextIndex = 0;
      } else if (e.key === "End") {
        nextIndex = links.length - 1;
      } else {
        return;
      }
      e.preventDefault();
      links[nextIndex].focus();
    });
  }

  document
    .querySelectorAll(".sidebar ul, .modeling-sidebar ul")
    .forEach(enableArrowNavigation);

  // ===== SNOWFALL (skipped for reduced-motion users) =====
  const snowfallContainer = document.getElementById("snowfall");
  const prefersReducedMotion = window.matchMedia(
    "(prefers-reduced-motion: reduce)",
  ).matches;
  const snowflakeChars = ["❄", "•", "◦"];
  const snowflakeCount = prefersReducedMotion ? 0 : 40;

  for (let i = 0; i < snowflakeCount; i++) {
    const flake = document.createElement("span");
    flake.classList.add("snowflake");
    flake.textContent =
      snowflakeChars[Math.floor(Math.random() * snowflakeChars.length)];
    flake.style.left = Math.random() * 100 + "%";
    flake.style.fontSize = Math.random() * 8 + 8 + "px";
    flake.style.animationDuration = Math.random() * 15 + 20 + "s";
    flake.style.animationDelay = Math.random() * -30 + "s";
    flake.style.setProperty("--drift", Math.random() * 80 - 40 + "px");
    flake.style.opacity = Math.random() * 0.3 + 0.2;
    snowfallContainer.appendChild(flake);
  }

  // Show Profile by default
  document.getElementById("profile").classList.add("active");

  // ===== SCROLL PROGRESS =====
  const scrollProgress = document.getElementById("scrollProgress");
  window.addEventListener("scroll", () => {
    const scrollTop = window.scrollY;
    const docHeight =
      document.documentElement.scrollHeight - window.innerHeight;
    const scrollPercent = (scrollTop / docHeight) * 100;
    scrollProgress.style.width = scrollPercent + "%";
  });

  // ===== BACK TO TOP =====
  const backToTop = document.getElementById("backToTop");
  window.addEventListener("scroll", () => {
    if (window.scrollY > 300) {
      backToTop.classList.add("visible");
    } else {
      backToTop.classList.remove("visible");
    }
  });
  backToTop.addEventListener("click", () => {
    window.scrollTo({ top: 0, behavior: "smooth" });
  });

  // ===== THEME TOGGLE (saved choice wins, else OS preference) =====
  const themeToggle = document.getElementById("themeToggle");
  const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;

  function resolvedTheme() {
    return localStorage.getItem("theme") || (prefersDark ? "dark" : "light");
  }

  // The inline head script already applied this before first paint
  document.documentElement.setAttribute("data-theme", resolvedTheme());

  themeToggle.addEventListener("click", () => {
    const newTheme =
      document.documentElement.getAttribute("data-theme") === "dark"
        ? "light"
        : "dark";
    document.documentElement.setAttribute("data-theme", newTheme);
    localStorage.setItem("theme", newTheme);
  });

  // ===== LIGHTBOX =====
  const lightbox = document.getElementById("lightbox");
  const lightboxClose = document.getElementById("lightboxClose");
  const lightboxMedia = document.getElementById("lightboxMedia");
  const lightboxCaption = document.getElementById("lightboxCaption");

  // Add click handlers to images with data-lightbox
  document.querySelectorAll('[data-lightbox="true"]').forEach((img) => {
    img.addEventListener("click", (e) => {
      e.stopPropagation();
      const src = img.src;
      const alt = img.alt;
      lightboxMedia.innerHTML = `<img src="${src}" alt="${alt}">`;
      lightboxCaption.textContent = alt;
      lightbox.classList.add("active");
      document.body.style.overflow = "hidden";
    });
  });

  lightboxClose.addEventListener("click", (e) => {
    e.stopPropagation();
    lightbox.classList.remove("active");
    document.body.style.overflow = "";
  });

  lightbox.addEventListener("click", () => {
    lightbox.classList.remove("active");
    document.body.style.overflow = "";
  });

  // Close with Escape key
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && lightbox.classList.contains("active")) {
      lightbox.classList.remove("active");
      document.body.style.overflow = "";
    }
  });

  // ===== INTERSECTION OBSERVER FOR ANIMATIONS =====
  const observerOptions = {
    threshold: 0.1,
    rootMargin: "0px 0px -50px 0px",
  };

  const animationObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.style.opacity = "1";
        entry.target.style.transform = "translateY(0)";
      }
    });
  }, observerOptions);

  // Observe timeline items, project cards, and highlight cards
  document
    .querySelectorAll(".timeline-item, .project-card, .highlight-card")
    .forEach((el) => {
      el.style.opacity = "0";
      el.style.transform = "translateY(20px)";
      el.style.transition = "opacity 0.6s ease, transform 0.6s ease";
      animationObserver.observe(el);
    });

  // Stagger the animations
  document.querySelectorAll(".timeline-item").forEach((item, index) => {
    item.style.transitionDelay = `${index * 0.1}s`;
  });
  document.querySelectorAll(".project-card").forEach((card, index) => {
    card.style.transitionDelay = `${index * 0.1}s`;
  });
  document.querySelectorAll(".highlight-card").forEach((card, index) => {
    card.style.transitionDelay = `${index * 0.15}s`;
  });
});
